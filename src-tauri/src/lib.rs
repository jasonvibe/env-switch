use std::sync::Mutex;
use tauri::{AppHandle, Emitter, State};
use models::StoreData;

pub struct AppState {
    pub store: Mutex<StoreData>,
}

#[tauri::command]
fn get_store(state: State<'_, AppState>) -> Result<StoreData, String> {
    let store = state.store.lock().map_err(|e| e.to_string())?;
    Ok(store.clone())
}

#[tauri::command]
fn save_store_data(new_data: StoreData, state: State<'_, AppState>) -> Result<(), String> {
    let mut store = state.store.lock().map_err(|e| e.to_string())?;
    *store = new_data.clone();
    storage::save_store(&new_data)?;
    Ok(())
}

#[tauri::command]
fn apply_profile(profile_id: String, state: State<'_, AppState>, app: AppHandle) -> Result<Vec<String>, String> {
    let mut store = state.store.lock().map_err(|e| e.to_string())?;
    let keys = system_env::apply_profile_to_system(&profile_id, &mut store)?;
    storage::save_store(&store)?;

    // Emit event to notify frontend
    let _ = app.emit("profile-switched", profile_id);

    Ok(keys)
}

#[tauri::command]
fn clear_system_env(state: State<'_, AppState>, app: AppHandle) -> Result<(), String> {
    let mut store = state.store.lock().map_err(|e| e.to_string())?;
    system_env::clear_system_env(&mut store)?;
    storage::save_store(&store)?;

    let _ = app.emit("system-env-cleared", ());
    Ok(())
}

#[tauri::command]
fn set_secret_val(profile_id: String, key: String, secret: String) -> Result<(), String> {
    keychain::save_secret(&profile_id, &key, &secret)
}

#[tauri::command]
fn get_secret_val(profile_id: String, key: String) -> Result<String, String> {
    keychain::get_secret(&profile_id, &key)
}

#[tauri::command]
fn parse_env_text(content: String) -> Result<Vec<(String, String)>, String> {
    let mut list = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }

        // strip optional "export "
        let clean = if trimmed.starts_with("export ") {
            trimmed.trim_start_matches("export ").trim()
        } else {
            trimmed
        };

        if let Some((k, v)) = clean.split_once('=') {
            let key = k.trim().to_string();
            let mut val = v.trim().to_string();

            // strip outer quotes if present
            if (val.starts_with('"') && val.ends_with('"')) || (val.starts_with('\'') && val.ends_with('\'')) {
                if val.len() >= 2 {
                    val = val[1..val.len() - 1].to_string();
                }
            }
            if !key.is_empty() {
                list.push((key, val));
            }
        }
    }
    Ok(list)
}

#[tauri::command]
fn export_profile_dotenv(profile_id: String, state: State<'_, AppState>) -> Result<String, String> {
    let store = state.store.lock().map_err(|e| e.to_string())?;
    let vars: Vec<_> = store.variables.iter()
        .filter(|v| v.profile_id == profile_id && v.enabled)
        .collect();

    let mut out = String::new();
    out.push_str("# Generated by EnvSwitch\n");
    for var in vars {
        let val = if var.is_secret {
            keychain::get_secret(&profile_id, &var.key).unwrap_or_default()
        } else {
            var.value.clone()
        };

        if !var.description.is_empty() {
            out.push_str(&format!("# {}\n", var.description));
        }
        out.push_str(&format!("{}={}\n", var.key, val));
    }
    Ok(out)
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let initial_store = storage::load_store().unwrap_or_default();

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .manage(AppState {
            store: Mutex::new(initial_store),
        })
        .setup(|app| {
            if let Err(e) = tray::create_tray(app.handle()) {
                eprintln!("Failed to create system tray: {}", e);
            }
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            get_store,
            save_store_data,
            apply_profile,
            clear_system_env,
            set_secret_val,
            get_secret_val,
            parse_env_text,
            export_profile_dotenv
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_env_text() {
        let sample = r#"
        # System settings
        PORT=8080
        export DATABASE_URL="postgres://user:pass@localhost:5432/db"
        API_SECRET='sk_live_123456789'

        # Empty & whitespace lines
        
        DEBUG=true
        "#;

        let parsed = parse_env_text(sample.to_string()).unwrap();
        assert_eq!(parsed.len(), 4);
        assert_eq!(parsed[0], ("PORT".to_string(), "8080".to_string()));
        assert_eq!(parsed[1], ("DATABASE_URL".to_string(), "postgres://user:pass@localhost:5432/db".to_string()));
        assert_eq!(parsed[2], ("API_SECRET".to_string(), "sk_live_123456789".to_string()));
        assert_eq!(parsed[3], ("DEBUG".to_string(), "true".to_string()));
    }
}
